export function inferCategory(tags: string[] = [], productName = ""): string {
  const searchable = `${tags.join(" ")} ${productName}`.toLocaleLowerCase("es");
  const match = CATEGORY_RULES.find(([keywords]) =>
    keywords.some((keyword) => searchable.includes(keyword)),
  );
  return match?.[1] || "Otros";
}
