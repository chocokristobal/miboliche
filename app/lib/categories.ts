const normalizeSearchText = (value: string) =>
  value.normalize("NFD").replace(/[\u0300-\u036f]/g, "").toLocaleLowerCase("es");

export function categoryDisplayName(category: string): string {
  return CATEGORY_LABELS[category] || category;
}

export function categoryMatchesSearch(category: string, query: string): boolean {
  const searchable = [
    category,
    categoryDisplayName(category),
    ...(CATEGORY_ALIASES[category] || []),
  ].join(" ");
  return normalizeSearchText(searchable).includes(normalizeSearchText(query));
}

